\set ON_ERROR_STOP on

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------- Справочники и структура колледжа -------------------------

CREATE TABLE specialties (
    specialty_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(10)  NOT NULL UNIQUE,
    name            VARCHAR(150) NOT NULL,
    qualification   VARCHAR(150) NOT NULL,
    duration_months SMALLINT     NOT NULL CHECK (duration_months BETWEEN 10 AND 72)
);

CREATE TABLE positions (
    position_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE teachers (
    teacher_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name   VARCHAR(50)  NOT NULL,
    first_name  VARCHAR(50)  NOT NULL,
    middle_name VARCHAR(50),
    position_id INTEGER      NOT NULL REFERENCES positions (position_id),
    hire_date   DATE         NOT NULL CHECK (hire_date >= DATE '1970-01-01'),
    email       VARCHAR(100) NOT NULL UNIQUE
                CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[a-z]+$'),
    phone       VARCHAR(20),
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE student_groups (
    group_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(20) NOT NULL UNIQUE,
    specialty_id   INTEGER     NOT NULL REFERENCES specialties (specialty_id),
    admission_year SMALLINT    NOT NULL CHECK (admission_year BETWEEN 2000 AND 2100),
    curator_id     INTEGER     REFERENCES teachers (teacher_id) ON DELETE SET NULL
);

CREATE TABLE student_statuses (
    status_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE students (
    student_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name       VARCHAR(50)  NOT NULL,
    first_name      VARCHAR(50)  NOT NULL,
    middle_name     VARCHAR(50),
    birth_date      DATE         NOT NULL CHECK (birth_date BETWEEN DATE '1980-01-01' AND DATE '2015-12-31'),
    gender          CHAR(1)      NOT NULL CHECK (gender IN ('М', 'Ж')),
    phone           VARCHAR(20),
    email           VARCHAR(100) NOT NULL UNIQUE
                    CHECK (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[a-z]+$'),
    address         VARCHAR(200),
    group_id        INTEGER      NOT NULL REFERENCES student_groups (group_id),
    status_id       INTEGER      NOT NULL DEFAULT 1 REFERENCES student_statuses (status_id),
    enrollment_date DATE         NOT NULL,
    expelled_date   DATE,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (expelled_date IS NULL OR expelled_date >= enrollment_date)
);

-- ---------- Учебный план и нагрузка ----------------------------------

CREATE TABLE disciplines (
    discipline_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL UNIQUE,
    cycle         VARCHAR(10)  NOT NULL CHECK (cycle IN ('ОГСЭ', 'ЕН', 'ОП', 'ПМ'))
);

CREATE TABLE control_types (
    control_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE curriculum (
    curriculum_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specialty_id    INTEGER  NOT NULL REFERENCES specialties (specialty_id) ON DELETE CASCADE,
    discipline_id   INTEGER  NOT NULL REFERENCES disciplines (discipline_id),
    semester        SMALLINT NOT NULL CHECK (semester BETWEEN 1 AND 8),
    hours           SMALLINT NOT NULL CHECK (hours > 0 AND hours <= 1500),
    control_type_id INTEGER  NOT NULL REFERENCES control_types (control_type_id),
    UNIQUE (specialty_id, discipline_id)
);

CREATE TABLE teaching_load (
    load_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      INTEGER NOT NULL REFERENCES student_groups (group_id) ON DELETE CASCADE,
    discipline_id INTEGER NOT NULL REFERENCES disciplines (discipline_id),
    teacher_id    INTEGER NOT NULL REFERENCES teachers (teacher_id),
    UNIQUE (group_id, discipline_id)
);

CREATE TABLE classrooms (
    classroom_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number       VARCHAR(10) NOT NULL UNIQUE,
    capacity     SMALLINT    NOT NULL CHECK (capacity BETWEEN 1 AND 300),
    room_type    VARCHAR(30) NOT NULL
                 CHECK (room_type IN ('Лекционная', 'Компьютерный класс', 'Лаборатория', 'Спортзал', 'Кабинет'))
);

-- ---------- Учебный процесс ------------------------------------------

CREATE TABLE lessons (
    lesson_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    load_id      INTEGER      NOT NULL REFERENCES teaching_load (load_id) ON DELETE CASCADE,
    classroom_id INTEGER      NOT NULL REFERENCES classrooms (classroom_id),
    lesson_date  DATE         NOT NULL,
    pair_number  SMALLINT     NOT NULL CHECK (pair_number BETWEEN 1 AND 7),
    lesson_type  VARCHAR(20)  NOT NULL
                 CHECK (lesson_type IN ('Лекция', 'Практика', 'Лабораторная', 'Контроль')),
    topic        VARCHAR(200),
    UNIQUE (classroom_id, lesson_date, pair_number)
);

CREATE TABLE grades (
    grade_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  INTEGER     NOT NULL REFERENCES students (student_id),
    lesson_id   INTEGER     NOT NULL REFERENCES lessons (lesson_id) ON DELETE CASCADE,
    grade_value SMALLINT    NOT NULL CHECK (grade_value BETWEEN 2 AND 5),
    grade_kind  VARCHAR(20) NOT NULL DEFAULT 'Текущая'
                CHECK (grade_kind IN ('Текущая', 'Контрольная', 'Зачётная')),
    graded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (student_id, lesson_id)
);

CREATE TABLE attendance (
    attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id     INTEGER     NOT NULL REFERENCES lessons (lesson_id) ON DELETE CASCADE,
    student_id    INTEGER     NOT NULL REFERENCES students (student_id),
    status        VARCHAR(25) NOT NULL
                  CHECK (status IN ('Присутствовал', 'Отсутствовал', 'Опоздал', 'Уважительная причина')),
    UNIQUE (lesson_id, student_id)
);

-- ---------- Служебные таблицы (безопасность и аудит) -----------------

CREATE TABLE app_users (
    user_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(40) NOT NULL UNIQUE,
    password_hash   TEXT        NOT NULL,
    role_name       VARCHAR(30) NOT NULL
                    CHECK (role_name IN ('role_admin', 'role_methodist', 'role_teacher', 'role_analyst')),
    teacher_id      INTEGER     REFERENCES teachers (teacher_id) ON DELETE SET NULL,
    is_active       BOOLEAN     NOT NULL DEFAULT TRUE,
    failed_attempts SMALLINT    NOT NULL DEFAULT 0,
    last_login      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_log (
    log_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    table_name VARCHAR(63) NOT NULL,
    operation  CHAR(1)     NOT NULL CHECK (operation IN ('I', 'U', 'D')),
    record_id  TEXT,
    old_data   JSONB,
    new_data   JSONB,
    changed_by TEXT        NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE student_private (
    student_id INTEGER PRIMARY KEY REFERENCES students (student_id) ON DELETE CASCADE,
    snils_enc  BYTEA       NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Индексы --------------------------------------------------
-- (индексы под PRIMARY KEY и UNIQUE создаются автоматически)

CREATE INDEX idx_students_group     ON students (group_id);
CREATE INDEX idx_students_lastname  ON students (lower(last_name) text_pattern_ops);
CREATE INDEX idx_students_active    ON students (group_id) WHERE expelled_date IS NULL;
CREATE INDEX idx_load_teacher       ON teaching_load (teacher_id);
CREATE INDEX idx_load_discipline    ON teaching_load (discipline_id);
CREATE INDEX idx_lessons_load       ON lessons (load_id);
CREATE INDEX idx_lessons_date_pair  ON lessons (lesson_date, pair_number);
CREATE INDEX idx_grades_lesson      ON grades (lesson_id);
CREATE INDEX idx_attendance_student ON attendance (student_id);
CREATE INDEX idx_audit_table_time   ON audit_log (table_name, changed_at DESC);

-- ---------- Комментарии ----------------------------------------------

