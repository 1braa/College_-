COMMENT ON TABLE curriculum      IS 'Учебный план: дисциплины специальности';
COMMENT ON TABLE teaching_load   IS 'Педагогическая нагрузка: преподаватель ведёт дисциплину в группе';
COMMENT ON TABLE lessons         IS 'Проведённые и запланированные занятия (расписание)';
